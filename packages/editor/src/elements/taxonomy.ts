/**
 * Fast lookup helper for category slug or id
 */
export function getCategoryBySlug(slug: string): AssetCategoryItem | undefined {
  return CANONICAL_TAXONOMY.find((c) => c.slug === slug || c.id === slug);
}

/**
 * Fast lookup helper for subcategory
 */
export function getSubcategory(categorySlug: string, subcategorySlug: string): AssetSubcategoryItem | undefined {
  const cat = getCategoryBySlug(categorySlug);
  return cat?.subcategories.find((s: AssetSubcategoryItem) => s.slug === subcategorySlug || s.id === subcategorySlug);
}
